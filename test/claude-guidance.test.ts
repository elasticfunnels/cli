test('ef status names the missing guidance, and stays quiet once it is declined', async () => {
    const dir = await fs.promises.realpath(await fs.promises.mkdtemp(path.join(os.tmpdir(), 'ef-cli-nudge-')));
    const server = http.createServer((_req, res) => {
        res.writeHead(200, { 'content-type': 'application/json' });
        res.end('[]');
    });
    await new Promise<void>((r) => server.listen(0, '127.0.0.1', () => r()));
    const port = (server.address() as { port: number }).port;
    const cfg = path.join(dir, '.ef', 'config.json');
    const run = (): Promise<string> => new Promise((resolve) => {
        const child = spawn(process.execPath, [BIN_PATH, 'status'], { cwd: dir, env: { ...process.env, NO_COLOR: '1' } });
        let err = '';
        child.stderr.on('data', (d) => (err += d));
        child.stdout.on('data', () => {});
        child.on('close', () => resolve(err));
    });
    try {
        await fs.promises.mkdir(path.join(dir, '.ef'), { recursive: true });
        const base = { apiUrl: `http://127.0.0.1:${port}`, brandId: 7, syncRoot: 'elasticfunnels', syncLayout: 'flat', saveMode: 'direct' };
        await fs.promises.writeFile(cfg, JSON.stringify(base));
        await fs.promises.writeFile(path.join(dir, '.ef', 'auth'), 'k\n');

        assert.match(await run(), /No AI guidance here/, 'an old project is told what it is missing');

        // A recorded refusal must silence it — the point of storing the choice.
        await fs.promises.writeFile(cfg, JSON.stringify({ ...base, aiGuidance: false }));
        assert.doesNotMatch(await run(), /No AI guidance here/, 'a declined project is not nagged');
    } finally {
        await new Promise<void>((r) => server.close(() => r()));
        await fs.promises.rm(dir, { recursive: true, force: true });
    }
});

test('guidance and skills agree on where a split test\'s intent is recorded', () => {
    // A test\'s numbers are on the server; the hypothesis and which arm is the
    // control exist only in the conversation that created it. If the creating
    // skill and the reading skill disagree about the filename, the record is
    // written where nothing looks for it.
    const guide = renderClaudeSection();
    assert.match(guide, /elasticfunnels\/split-tests\.md/);

    const root = path.resolve(__dirname, '..', '..', 'assets', 'skills');
    const events = fs.readFileSync(path.join(root, 'ef-page-events', 'SKILL.md'), 'utf8');
    const stats = fs.readFileSync(path.join(root, 'ef-stats', 'SKILL.md'), 'utf8');

    assert.match(events, /elasticfunnels\/split-tests\.md/, 'the skill that creates tests writes the record');
    assert.match(stats, /elasticfunnels\/split-tests\.md/, 'the skill that reads tests consults it');
    assert.match(events, /[Aa]ppend, never rewrite|append-only/, 'losing tests stay in the history');
    assert.match(events, /split test id/i, 'the id is the join key, since slugs get renamed');
});

test('guidance tells the agent to check the CLI version but not to install it', () => {
    // Two halves, and both matter. The notifier suppresses itself whenever
    // stderr is not a TTY — always true for an agent — so without being told,
    // an agent never learns the CLI is stale and quietly follows guidance for a
    // version it is not running. But `ef update` is a GLOBAL install: it
    // changes a binary shared with every other project on the machine, can need
    // sudo, and swaps the tool mid-task. Check, report, let the human decide.
    const text = renderClaudeSection();
    assert.match(text, /ef update --check/, 'the read-only check is named');
    assert.match(text, /[Dd]o not run `ef update` yourself/, 'installing is off-limits');
    assert.match(text, /global install/i, 'and the reason why is given');
});
